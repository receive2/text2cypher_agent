# ──────────────────────────────────────────────────────────────────────────────
# Tool-result backfill (safety net for the NER agent's lossy final synthesis)
# ──────────────────────────────────────────────────────────────────────────────

# Each generated tool's docstring opens with e.g. "Look up canonical
# AircraftModel.name values." — we parse the "Label.property" out of that so a
# ToolMessage can be mapped back to the entity-dict key it grounds. The
# " values" anchor keeps the match precise (avoids "e.g." / sentence noise).
_TOOL_KEY_RE = re.compile(r"\b([A-Za-z][A-Za-z0-9]*)\.([a-z][A-Za-z0-9_]*) values")


def _tool_key_map(mode: Optional[str]) -> Dict[str, str]:
    """Map each registry tool's func-name → its ``"Label.property"`` key,
    parsed from the tool description. Empty dict on any failure."""
    out: Dict[str, str] = {}
    try:
        reg = _get_registry(mode=mode)
    except Exception:  # noqa: BLE001 — backfill is best-effort
        return out
    for name, tool in reg.items():
        m = _TOOL_KEY_RE.search(getattr(tool, "description", "") or "")
        if m:
            out[name] = f"{m.group(1)}.{m.group(2)}"
    return out


def _parse_tool_values(content: Any) -> List[str]:
    """Best-effort parse a ``ToolMessage.content`` into ``List[str]`` of
    canonical values (best-first). The tool returns ``List[str]``; LangChain
    may hand it back as a list or a stringified list."""
    if isinstance(content, list):
        return [str(v) for v in content if str(v).strip()]
    s = str(content).strip()
    if not s:
        return []
    try:
        v = ast.literal_eval(s)
        if isinstance(v, list):
            return [str(x) for x in v if str(x).strip()]
        return [str(v)] if str(v).strip() else []
    except Exception:  # noqa: BLE001
        return [s]


def _backfill_from_tools(
    llm_dict:  Dict[str, Any],
    tool_msgs: List[ToolMessage],
    key_map:   Dict[str, str],
) -> Dict[str, Any]:
    """Safety-net backfill: re-attach groundings the NER agent *recovered via
    its own tool calls* but then dropped in its final-answer JSON synthesis.

    Conservative by construction — only **adds** keys that are missing (or
    empty) in ``llm_dict``; it never overrides a value the LLM emitted. Each
    harvested key takes the top-1 (best-match) canonical value from the first
    tool call that produced it.

    Fixes the dominant end-to-end grounding loss (see the NER funnel analysis):
    the ReAct agent calls the right value-lookup tool, gets the canonical value
    at rank-1, but its final message returns ``{}`` — so nothing is injected and
    the Cypher LLM falls back to the question's perturbed surface form.
    """
    harvested: Dict[str, str] = {}
    for tm in tool_msgs:
        key = key_map.get(getattr(tm, "name", "") or "")
        if not key or key in harvested:
            continue
        vals = _parse_tool_values(tm.content)
        if vals:
            harvested[key] = vals[0]
    if not harvested:
        return llm_dict
    merged = dict(llm_dict)
    for key, val in harvested.items():
        cur = merged.get(key)
        if cur is None or cur == "" or cur == []:
            merged[key] = val
    return merged


def get_ner_auto(
    prompt:    str,
    top_k:     int  = DEFAULT_TOP_K,
    faiss_dir: Optional[str] = None,
    rebuild:   bool = False,
    verbose:   bool = False,
    llm_obj:   Optional[BaseChatModel] = None,
    mode:      Optional[str] = None,
) -> str:
    """
    Run the NER agent on *prompt* with auto-selected tools and return a
    canonical JSON string.

    This is the ``ner_agent_auto`` counterpart of ``ner_agent.get_ner()``.
    The return format is identical::

        '{"Movie.title": ["The Matrix"], "Movie.released": [1999]}'

    Parameters
    ----------
    prompt    : User's natural-language question.
    top_k     : Number of tools to select (default 5).
    faiss_dir : FAISS index directory.
    rebuild   : Force-rebuild the FAISS tool index.
    verbose   : Stream agent messages and print tool-selection details.
    llm_obj   : Optional ``BaseChatModel`` to drive the NER agent.
                When *None*, the module-level default ``llm`` is used.

    Returns
    -------
    str  Canonical JSON string (``"{}"`` on failure).
    """
    effective_mode = _resolve_mode(mode)
    if effective_mode == "no_ner":
        # Short-circuit: skip the ReAct agent entirely and return the empty
        # entity dict.  Downstream code (ask_auto / cypher prompt) treats
        # an empty dict as "no entity hints" and lets the LLM generate
        # Cypher purely from the question + schema.
        if verbose:
            logger.info(
                "get_ner_auto: NER mode='no_ner' — skipping ReAct agent, "
                "returning empty entity dict."
            )
        return "{}"

    # ``rag`` is a constrained variant: it uses the same tool scope as
    # ``react_node_rel`` (node + relation) but caps the ReAct loop at a single
    # tool-call round and disables the backfill safety net (see below).
    is_rag    = effective_mode == "rag"
    tool_mode = "react_node_rel" if is_rag else effective_mode

    inputs      = {"messages": [("user", prompt)]}
    agent_graph = create_agent_auto(
        user_query = prompt,
        top_k      = top_k,
        faiss_dir  = faiss_dir,
        rebuild    = rebuild,
        verbose    = verbose,
        llm_obj    = llm_obj,
        mode       = tool_mode,
    )

    message = None
    tool_msgs: List[ToolMessage] = []
    # Normal modes: ``recursion_limit=8`` caps the ReAct loop at ~4 think/act
    # pairs (NER usually resolves in 2–4 LLM calls; beyond ~8 is the model
    # spinning). RAG mode: ``RAG_RECURSION_LIMIT`` (≈3) allows a single tool
    # round (agent → tools → agent) and then forces the answer — no iterative
    # refinement.
    rec_limit = RAG_RECURSION_LIMIT if is_rag else 8
    try:
        for msgs in agent_graph.stream(
            inputs,
            stream_mode="values",
            config={"recursion_limit": rec_limit},
        ):
            tool_msgs = [m for m in msgs["messages"] if isinstance(m, ToolMessage)]
            message   = msgs["messages"][-1]

            if verbose:
                if isinstance(message, tuple):
                    logger.info(message)
                else:
                    message.pretty_print()
                for tm in tool_msgs:
                    logger.info(tm.content)
    except GraphRecursionError:
        # RAG intentionally runs a tight recursion budget; if the model tries a
        # second tool round we stop and use whatever the first round produced
        # rather than erroring the example. (Normal modes use a generous budget,
        # so hitting this there is the rare genuine-spin case — same handling.)
        if verbose:
            logger.info(
                f"get_ner_auto: recursion_limit={rec_limit} reached "
                f"(mode={effective_mode}); using the partial result."
            )

    if message is None:
        return "{}"

    final_json = extract_content(message.content)

    if is_rag:
        # RAG baseline: NO backfill — return the agent's single-round output
        # verbatim. This is the whole point of the mode (measure one retrieval
        # round of the LLM agent, without the tool-result safety net).
        return final_json

    # ── Safety net: backfill groundings the agent recovered but dropped ───────
    # The ReAct agent's final-answer JSON sometimes drops a canonical value its
    # own tool call already returned at rank-1 (returns {} or omits a key). We
    # re-attach those from the tool-call history — additively, never overriding
    # what the LLM emitted. See _backfill_from_tools.
    try:
        llm_dict = json.loads(final_json)
        if not isinstance(llm_dict, dict):
            llm_dict = {}
    except Exception:  # noqa: BLE001
        llm_dict = {}
    merged = _backfill_from_tools(llm_dict, tool_msgs, _tool_key_map(effective_mode))
    if verbose and merged != llm_dict:
        logger.info(
            "get_ner_auto: tool-backfill added "
            f"{ {k: merged[k] for k in merged if k not in llm_dict} }"
        )
    return json.dumps(merged, ensure_ascii=False)


def get_ner_dict_auto(
    prompt:    str,
    top_k:     int  = DEFAULT_TOP_K,
    faiss_dir: Optional[str] = None,
    rebuild:   bool = False,
    verbose:   bool = False,
    llm_obj:   Optional[BaseChatModel] = None,
    mode:      Optional[str] = None,
) -> Dict[str, Any]:
    """
    Convenience wrapper around :func:`get_ner_auto` that returns a Python dict
    instead of a JSON string.

    Returns
    -------
    dict
        Canonical entity dict.  Values follow the scalar-or-list convention:

        - single value  → bare scalar (e.g. ``"Inception"`` or ``2015``)
        - multiple values (2+) → list (e.g. ``["Neo", "Morpheus"]``)
        - no match → key omitted

        Returns ``{}`` on parse failure.
    """
    raw = get_ner_auto(
        prompt    = prompt,
        top_k     = top_k,
        faiss_dir = faiss_dir,
        rebuild   = rebuild,
        verbose   = verbose,
        llm_obj   = llm_obj,
        mode      = mode,
    )
    try:
        obj = json.loads(raw)
        return obj if isinstance(obj, dict) else {}
    except Exception:
        return {}


