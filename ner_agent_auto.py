# Cypher generation prompt template.
#
# Single source of truth: ``agent/prompts.py:TEXT2CYPHER_SP``, which is
# auto-generated by ``schema/gen_system_prompt.py`` and is the file picked
# up by ``eval/artifact_swap.py`` for per-graph specialisation (each graph
# gets its own baked schema + few-shot examples under
# ``setup_artifacts/<graph>/agent/prompts.py``).
#
# Re-exported here as ``CYPHER_TEMPLATE`` so older callers / scripts that
# still reference the symbol keep working.  ``{relevant_entities}`` is
# filled at runtime with the NER output; ``{schema}`` and ``{question}``
# are handled by GraphCypherQAChain.
CYPHER_TEMPLATE = TEXT2CYPHER_SP


def ask_auto(
    prompt:        str,
    top_k:         int  = DEFAULT_TOP_K,
    faiss_dir:     Optional[str] = None,
    rebuild:       bool = False,
    verbose:       bool = False,
    ner_llm:       Optional[BaseChatModel] = None,
    qa_llm:        Optional[BaseChatModel] = None,
    cypher_llm:    Optional[BaseChatModel] = None,
    mode:          Optional[str] = None,
) -> Dict[str, Any]:
    """
    Full end-to-end pipeline with auto tool selection:

    1. **NER** — :func:`get_ner_auto` extracts canonical entity values using
       only the FAISS-selected, connectivity-filtered tools.
    2. **Cypher generation** — injects the extracted entities into
       ``CYPHER_TEMPLATE`` and passes it to ``GraphCypherQAChain`` which asks
       the LLM to write a Cypher query against the actual schema.
    3. **Execution** — the chain runs the Cypher query on the connected
       Neo4j graph and formats the rows into a natural-language answer.

    The pipeline uses **three independent LLM slots** so experiments can mix
    providers freely (e.g. GPT for NER, Claude Opus for Cypher):

    ============ ========================================================
    Slot          Role
    ============ ========================================================
    ``ner_llm``   Drives the LangGraph ReAct agent that does entity NER.
    ``qa_llm``    "Value-linking" LLM passed to ``GraphCypherQAChain.from_llm``
                  via ``llm=`` — formats Cypher results into natural language.
    ``cypher_llm`` Generates the Cypher query from the schema + question.
    ============ ========================================================

    Each slot defaults to the **configured singleton** from ``config.py``
    when *None* is passed (``NER_LLM_CONFIG`` / ``QA_LLM_CONFIG`` /
    ``CYPHER_LLM_CONFIG``), so callers don't need to thread LLM objects
    through their code — just edit ``config.py`` once and re-import.

    Parameters
    ----------
    prompt    : User's natural-language question.
    top_k     : Number of tools to select via FAISS (default 5).
    faiss_dir : FAISS tool-index directory.
    rebuild   : Force-rebuild the FAISS index before running.
    verbose   : Stream agent messages, print tool-selection decisions, and
                enable ``GraphCypherQAChain`` verbose mode.
    ner_llm    : LLM for the NER agent stage.
                 Defaults to ``agent_helper.ner_llm`` (config.NER_LLM_CONFIG).
    qa_llm     : LLM for the answer-formatting (value-linking) stage in
                 ``GraphCypherQAChain``.
                 Defaults to ``agent_helper.qa_llm`` (config.QA_LLM_CONFIG).
    cypher_llm : LLM for the Cypher-generation stage in
                 ``GraphCypherQAChain``.
                 Defaults to ``agent_helper.cypher_llm`` (config.CYPHER_LLM_CONFIG).

    Returns
    -------
    dict with keys:

    =========== ============================================================
    ``entities`` Canonical entity JSON string.  Single matches are emitted
                 as bare scalars; multi-value matches as JSON arrays.  E.g.
                 ``'{"Movie.released": 2015}'`` (single) or
                 ``'{"ACTED_IN.roles": ["Neo", "Morpheus"]}'`` (multi).
    ``cypher``   The Cypher query generated by the LLM.
    ``result``   Natural-language answer produced by the QA LLM.
    ``context``  Raw list of dicts returned by Neo4j before formatting.
    =========== ============================================================

    Example
    -------
    >>> # Default — all three slots use the singletons built from config.py.
    >>> # Edit NER_LLM_CONFIG / QA_LLM_CONFIG / CYPHER_LLM_CONFIG in config.py
    >>> # to switch providers; no other code changes are required.
    >>> out = ask_auto("How many movies were released before 2000?")

    >>> # One-off override: keep config.py defaults for NER + QA, but try
    >>> # Claude Opus for Cypher generation only.
    >>> from agent_helper import build_llm
    >>> opus = build_llm(provider="anthropic", model="claude-opus-4-20250514")
    >>> out  = ask_auto(
    ...     "How many movies were released before 2000?",
    ...     cypher_llm = opus,
    ... )
    """
    # ── Resolve LLM slots ─────────────────────────────────────────────────────
    # Each slot defaults to the configured singleton built from config.py:
    #     ner_llm    → config.NER_LLM_CONFIG
    #     qa_llm     → config.QA_LLM_CONFIG
    #     cypher_llm → config.CYPHER_LLM_CONFIG
    # Pass an explicit ``BaseChatModel`` to override at runtime.
    ner_llm_eff    = ner_llm    if ner_llm    is not None else _ner_llm
    qa_llm_eff     = qa_llm     if qa_llm     is not None else _qa_llm
    cypher_llm_eff = cypher_llm if cypher_llm is not None else _cypher_llm

    # ── Resolve value-linking spec (four axes) ────────────────────────────────
    spec = resolve_spec(mode)
    effective_mode = spec.canonical   # flat name the rest of this fn keys on
    # RETRIEVAL_TYPE drives the react grounder's retrieval backend via the
    # vector_config global the generated node tools read at call time. (plan_exec
    # selects fuzzy/hybrid explicitly per search_tool call; rag / no_ner leave
    # the global untouched.)
    if spec.val_link == "val_link" and spec.agent == "react":
        import vector_config as _vc
        _vc.TOOL_RETRIEVAL_MODE = spec.retrieval
    if verbose:
        print(f"\n── value-linking spec ──────────────────────────────────────────────")
        print(f"  {spec}  (canonical={effective_mode})")

    # ── Step 1: entity extraction (NER) ───────────────────────────────────────
    # ``plan_exec`` produces a free-text candidate block (per-mention top-K
    # values) rather than a ``{Label.prop: value}`` JSON dict, so it bypasses
    # the JSON normalisation below and is injected verbatim.
    plan_exec_block: Optional[str] = None
    if effective_mode == "no_ner":
        entities = "{}"
        if verbose:
            print(
                "\n── Extracted entities ──────────────────────────────────────────────"
            )
            print(f"  {entities}  (NER skipped — mode='no_ner')")
    elif effective_mode == "fcav":
        # Standard retrieve-then-generate RAG baseline: embed the question,
        # retrieve candidate values from the self-built FCAV value index, and
        # let an LLM generate the {Label.prop: value} entity JSON (see fcav.py).
        from fcav import get_fcav_entities
        entities = get_fcav_entities(prompt, verbose=verbose)
        if verbose:
            print(f"\n── Extracted entities (FCAV retrieve→generate) ──")
            print(f"  {entities}")
    elif _is_plan_exec(effective_mode):
        from plan_exec import get_plan_exec_evidence
        import config as _config
        plan_exec_block = get_plan_exec_evidence(
            prompt, llm_obj=ner_llm_eff,
            node_only=(spec.tool == "node"),
            hybrid=(spec.retrieval == "hybrid"),
            escalate=_config.PLAN_EXEC_ESCALATE,
            verbose=verbose,
        )
        entities = plan_exec_block
        if verbose:
            print(f"\n── Extracted entities (plan_exec candidate block) ──")
            print(f"  {entities}")
    else:
        entities = get_ner_auto(
            prompt    = prompt,
            top_k     = top_k,
            faiss_dir = faiss_dir,
            rebuild   = rebuild,
            verbose   = verbose,
            llm_obj   = ner_llm_eff,
            mode      = effective_mode,
        )
        if verbose:
            print(f"\n── Extracted entities ──────────────────────────────────────────────")
            print(f"  {entities}")

    # ── Step 2: build the filled Cypher prompt ────────────────────────────────
    # Defensive normalisation: collapse any 1-element list to a scalar and
    # flatten nested ``[[v1],[v2]]`` shapes before injection.  ``extract_content``
    # already does this for outputs that pass through it, but this second pass
    # is a belt-and-suspenders guarantee that the Cypher LLM never sees a
    # stray wrapper such as ``["Inception"]`` (which it would otherwise be
    # tempted to copy verbatim into the query).  Skipped for ``plan_exec``,
    # whose block is free text, not a JSON entity dict.
    if plan_exec_block is None:
        entities = _normalize_for_injection(entities)
    if verbose:
        print(f"\n── Entities (post-normalisation, injected to Cypher LLM) ──")
        print(f"  {entities}")

    # Escape curly braces in the entity JSON so PromptTemplate doesn't treat
    # them as placeholder markers (e.g. {"Movie.released": 2015} → safe).
    safe_entities = entities.replace("{", "{{").replace("}", "}}")
    filled = CYPHER_TEMPLATE.replace("{relevant_entities}", safe_entities)

    cypher_prompt = PromptTemplate(
        input_variables=["schema", "question"],
        template=filled,
    )

    # ── Step 3: build GraphCypherQAChain and run ──────────────────────────────
    chain = GraphCypherQAChain.from_llm(
        graph                    = neo4j_graph,
        llm                      = qa_llm_eff,      # value linking LLM
        cypher_llm               = cypher_llm_eff,  # Cypher generation LLM
        cypher_prompt            = cypher_prompt,
        verbose                  = verbose,
        allow_dangerous_requests = True,
        return_intermediate_steps= True,
    )

    response = chain.invoke({"query": prompt})

    # ── Step 4: extract Cypher + raw context from intermediate steps ──────────
    cypher_query: str  = ""
    context:      list = []
    for step in response.get("intermediate_steps", []):
        if isinstance(step, dict):
            if "query" in step and not cypher_query:
                cypher_query = str(step["query"]).strip()
            if "context" in step:
                context = step["context"]

    result = str(response.get("result", "")).strip()

    if verbose:
        print(f"\n── Generated Cypher ────────────────────────────────────────────────")
        print(f"  {cypher_query}")
        print(f"\n── Answer ──────────────────────────────────────────────────────────")
        print(f"  {result}")

    return {
        "entities": entities,
        "cypher":   cypher_query,
        "result":   result,
        "context":  context,
        "mode":     effective_mode,
    }


