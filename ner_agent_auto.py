# 3. Tool registry  — scan generated modules for @tool instances
# ──────────────────────────────────────────────────────────────────────────────

def build_tool_registry(mode: Optional[str] = None) -> Dict[str, BaseTool]:
    """
    Import the generated tool modules and return a registry mapping
    ``func_name → BaseTool``.

    Which modules are loaded depends on the resolved NER *mode*:

    ====== ============================================================
    mode    Modules loaded
    ====== ============================================================
    ``"full"``       ``generated_node_tools`` + ``generated_rel_tools``
    ``"node_only"``  ``generated_node_tools`` only (relation tools dropped)
    ``"no_ner"``     no modules — the registry is empty because the agent
                     is bypassed entirely (callers must check the mode
                     before relying on the registry).
    ====== ============================================================

    Parameters
    ----------
    mode : str | None
        Explicit canonical grounding-mode override.  See :func:`_resolve_mode`.

    Raises
    ------
    RuntimeError
        If *mode* expects tool modules but none can be imported (i.e.
        ``gen_tools.py`` has not been run yet).
    """
    effective = _resolve_mode(mode)

    if effective == "no_ner":
        logger.info("Tool registry skipped — NER mode is 'no_ner'.")
        return {}

    if _is_node_only(effective):
        target_modules = ("generated.generated_node_tools",)
    else:                           # node + relation tool scope
        target_modules = ("generated.generated_node_tools", "generated.generated_rel_tools")

    modules = []
    for mod_name in target_modules:
        try:
            mod = importlib.import_module(mod_name)
            importlib.reload(mod)          # pick up fresh re-generations
            modules.append(mod)
            logger.debug(f"Imported {mod_name!r}")
        except ImportError:
            logger.warning(
                f"Could not import {mod_name!r}. "
                "Run `python gen_tools.py` to generate it."
            )

    if not modules:
        raise RuntimeError(
            f"No generated tool modules found for NER mode {effective!r}. "
            "Please run `python gen_tools.py` first to create "
            "`generated_node_tools.py` and `generated_rel_tools.py`."
        )

    registry = build_tool_registry_from_modules(modules)
    logger.info(
        f"Tool registry built (mode={effective!r}): {len(registry)} tools loaded."
    )
    return registry


# ──────────────────────────────────────────────────────────────────────────────
# 4. Module-level lazy singletons for registry and FAISS
# ──────────────────────────────────────────────────────────────────────────────

# Cached per-mode so switching mode at runtime (e.g. for an evaluation
# sweep) doesn't force every call to rebuild the registry / FAISS index.
_registry_by_mode:    Dict[str, Dict[str, BaseTool]] = {}
_vectorstore_by_mode: Dict[str, Any]                 = {}
_embeddings                                          = None


def _get_registry(mode: Optional[str] = None) -> Dict[str, BaseTool]:
    """Return the tool registry for the resolved *mode*, building on first call."""
    effective = _resolve_mode(mode)
    if effective not in _registry_by_mode:
        _registry_by_mode[effective] = build_tool_registry(mode=effective)
    return _registry_by_mode[effective]


def _get_embeddings():
    """Return the shared embeddings client, building it on first call."""
    global _embeddings
    if _embeddings is None:
        _embeddings = build_embeddings()
    return _embeddings


def _get_vectorstore(
    faiss_dir: Optional[str] = None,
    rebuild:   bool          = False,
    mode:      Optional[str] = None,
):
    """Return the FAISS vectorstore for *mode*, building / loading on first call.

    Each tool scope has its own FAISS directory (see ``_faiss_dir``) so the
    indexes for ``"full"`` and ``"node_only"`` never collide.

    The ``"no_ner"`` mode never touches FAISS — callers must guard against
    invoking this function in that mode.
    """
    effective = _resolve_mode(mode)
    if effective == "no_ner":
        raise RuntimeError(
            "_get_vectorstore() is not callable in NER mode 'no_ner' — "
            "the ReAct agent is bypassed entirely."
        )

    target_dir = faiss_dir or _faiss_dir(effective)

    cached = _vectorstore_by_mode.get(effective)
    if cached is None or rebuild:
        cached = get_or_build_tools_faiss(
            registry   = _get_registry(mode=effective),
            faiss_dir  = target_dir,
            rebuild    = rebuild,
            embeddings = _get_embeddings(),
            ner_mode   = _faiss_scope(effective),
        )
        _vectorstore_by_mode[effective] = cached
    return cached


# ──────────────────────────────────────────────────────────────────────────────
# 5. Tool selection
# ──────────────────────────────────────────────────────────────────────────────

def select_tools_for_query(
    user_query:           str,
    top_k:                int  = DEFAULT_TOP_K,
    faiss_dir:            Optional[str] = None,
    rebuild:              bool = False,
    filter_connectivity:  bool = True,
    verbose:              bool = False,
    mode:                 Optional[str] = None,
) -> List[BaseTool]:
    """
    Use FAISS semantic search to select the *top_k* most relevant tools for
    *user_query* from the full tool registry, then optionally top up the
    selection with the node tools needed to complete each selected
    relation's endpoint coverage.

    Parameters
    ----------
    user_query           : Natural-language question or instruction.
    top_k                : Maximum number of tools to return from FAISS
                           (default 5).  Connectivity top-up may add a
                           handful of extra node tools on top of this.
    faiss_dir            : Directory of the FAISS index (built automatically if absent).
    rebuild              : Force-rebuild the FAISS index even if it already exists.
    filter_connectivity  : When *True* (default), call
                           :func:`filter_tools_by_connectivity` after FAISS
                           search to **additively** ensure that every
                           selected relation tool's endpoint node labels
                           also have a node tool registered with the agent.
                           No tool is ever dropped -- only appended.
                           Set to *False* to skip the top-up and use the
                           raw FAISS hits as-is.
    verbose              : Print ranked hits and filter decisions to stdout.

    Returns
    -------
    List[BaseTool]
        Ordered as: FAISS hits (most → least relevant) followed by any
        appended endpoint-coverage node tools.

    Example
    -------
    >>> tools = select_tools_for_query("who played Neo in The Matrix", top_k=2)
    >>> [t.name for t in tools]
    ['get_acted_in_roles', 'get_movie_title', 'get_person_name']
    # FAISS returned [get_acted_in_roles, get_movie_title]; ACTED_IN
    # connects Person↔Movie, Movie is already covered by get_movie_title,
    # so the connectivity top-up appended get_person_name to cover Person.
    """
    effective_mode = _resolve_mode(mode)
    if effective_mode == "no_ner":
        # The agent is bypassed in this mode, so there are no tools to select.
        if verbose:
            print(
                f"\n── Tool selection skipped (NER mode='no_ner') for: "
                f"{user_query!r} ──"
            )
        return []

    vs   = _get_vectorstore(faiss_dir=faiss_dir, rebuild=rebuild, mode=effective_mode)
    hits = search_tools(vs, user_query=user_query, top_l=top_k)

    if verbose:
        print(
            f"\n── Tool selection for: {user_query!r} "
            f"(top_k={top_k}, mode={effective_mode!r}) ──"
        )
        for h in hits:
            print(f"  [{h.rank}] score={h.score:.4f}  {h.func_name}  — {h.description[:80]}")

    tools = hits_to_callables(hits, _get_registry(mode=effective_mode))

    if filter_connectivity:
        tools = filter_tools_by_connectivity(
            tools,
            registry=_get_registry(mode=effective_mode),
            verbose=verbose,
        )

    return tools


# ──────────────────────────────────────────────────────────────────────────────
# 5.5  Connectivity filter — drop relation tools that don't connect to any
#      node label covered by the selected node tools
# ──────────────────────────────────────────────────────────────────────────────

# Pre-compiled patterns used by the helpers below.
_RE_NODE_DESC       = re.compile(r"canonical\s+(\w+)\.(\w+)\s+values")
_RE_STRUCTURAL_DESC = re.compile(
    r"via\s+\(:(\w+)\)-\[:(\w+)\]->\(:(\w+)\)"
)
_RE_ALL_CAPS        = re.compile(r"^[A-Z][A-Z_]+$")   # rel type (e.g. ACTED_IN)
_RE_PASCAL          = re.compile(r"^[A-Z][a-z]\w*$")  # node label (e.g. Movie)


_SCHEMA_META_PATH: str = str(SCHEMA_META)


def _load_rel_connectivity_from_meta(
    meta_path: Union[str, Path] = _SCHEMA_META_PATH,
) -> Optional[Dict[str, Set[str]]]:
    """
    Read ``schema_meta.json`` and return ``{rel_type: {label, …}}`` built from
    the ``endpoints`` field persisted by ``gen_schema_meta.py``.

    Returns
    -------
    dict
        Connectivity map when the meta file exposes the new ``endpoints``
        field on at least one relationship.
    None
        When the file is absent, malformed, or pre-dates the ``endpoints``
        field — in which case callers should fall back to the legacy
        description-parsing path.
    """
    try:
        with open(meta_path, encoding="utf-8") as fh:
            meta = json.load(fh)
    except FileNotFoundError:
        logger.warning(
            "schema_meta.json not found at {!r}; falling back to "
            "description parsing for relationship connectivity. "
            "Run gen_schema_meta.py to regenerate.", meta_path,
        )
        return None
    except json.JSONDecodeError as exc:
        logger.warning(
            "schema_meta.json could not be parsed ({}); falling back to "
            "description parsing for relationship connectivity.", exc,
        )
        return None

    rels = meta.get("relationships") or {}
    if not isinstance(rels, dict) or not rels:
        return None

    conn: Dict[str, Set[str]] = {}
    found_any = False
    for rt, info in rels.items():
        if not isinstance(info, dict):
            continue
        endpoints = info.get("endpoints")
        if not endpoints:
            continue
        found_any = True
        for ep in endpoints:
            if not isinstance(ep, dict):
                continue
            fl = ep.get("from")
            tl = ep.get("to")
            labels = {x for x in (fl, tl) if isinstance(x, str) and x}
            if labels:
                conn.setdefault(rt, set()).update(labels)

    if not found_any:
        logger.warning(
            "schema_meta.json lacks the 'endpoints' field on every "
            "relationship; falling back to description parsing. "
            "Re-run gen_schema_meta.py to regenerate with endpoints."
        )
        return None

    return conn


def _build_rel_connectivity_map(
    registry: Dict[str, BaseTool],
) -> Dict[str, Set[str]]:
    """
    Build a ``{rel_type: {label, …}}`` map describing which node labels each
    relationship type connects.

    Resolution order
    ----------------
    1. **Preferred** — read endpoints directly from ``schema_meta.json``.
       This is the single source of truth and covers *every* relationship
       type, including property-bearing ones (e.g. ``ACTED_IN``,
       ``REVIEWED``) whose connectivity is otherwise unrecoverable from tool
       descriptions because ``gen_tools.py`` does not emit structural
       traversal tools for them.
    2. **Fallback** — scan the registry for structural relation tool
       descriptions matching ``(:X)-[:Y]->(:Z)``.  Used only when
       ``schema_meta.json`` is missing or pre-dates the ``endpoints`` field;
       a warning is emitted recommending regeneration.

    The map is consumed by :func:`_get_tool_node_labels` to resolve the
    connected labels of relationship-property tools whose own descriptions
    don't mention node labels.
    """
    # ── Preferred: schema_meta.json (authoritative) ────────────────────────────
    from_meta = _load_rel_connectivity_from_meta()
    if from_meta is not None:
        return from_meta

    # ── Fallback: description parsing (legacy behaviour) ──────────────────────
    conn: Dict[str, Set[str]] = {}
    for tool_obj in registry.values():
        m = _RE_STRUCTURAL_DESC.search(tool_obj.description or "")
        if m:
            from_label = m.group(1)
            rel_type   = m.group(2)
            to_label   = m.group(3)
            conn.setdefault(rel_type, set()).update({from_label, to_label})
    return conn


def _is_rel_tool(tool_obj: BaseTool) -> bool:
    """
    Return *True* when *tool_obj* is a relation tool (property or structural).

    Heuristic:
    - Structural rel tool  → description contains ``"via (:"``
    - Rel-property tool    → description matches ``"canonical ALL_CAPS.prop"``
    """
    desc = tool_obj.description or ""
    if "via (:" in desc:
        return True
    m = _RE_NODE_DESC.search(desc)
    if m:
        return bool(_RE_ALL_CAPS.match(m.group(1)))
    return False


def _get_tool_node_labels(
    tool_obj: BaseTool,
    rel_conn: Dict[str, Set[str]],
) -> Set[str]:
    """
    Return the set of node labels that *tool_obj* relates to.

    ============== ======================================== =============
    Tool kind      Example description                      Labels
    ============== ======================================== =============
    Node           "canonical Movie.title values"           {"Movie"}
    Structural rel "via (:Person)-[:DIRECTED]->(:Movie)"    {"Person","Movie"}
    Rel property   "canonical ACTED_IN.roles values"        rel_conn["ACTED_IN"]
    ============== ======================================== =============

    Returns an empty set when the tool type cannot be determined.
    """
    desc = tool_obj.description or ""

    # ── Structural rel tool ────────────────────────────────────────────────────
    m = _RE_STRUCTURAL_DESC.search(desc)
    if m:
        return {m.group(1), m.group(3)}          # {from_label, to_label}

    # ── Node tool or rel-property tool ────────────────────────────────────────
    m = _RE_NODE_DESC.search(desc)
    if m:
        word = m.group(1)
        if _RE_ALL_CAPS.match(word):
            # Rel-property tool — look up connected labels from the map
            return rel_conn.get(word, set())
        if _RE_PASCAL.match(word):
            # Node tool
            return {word}

    return set()


def filter_tools_by_connectivity(
    selected_tools: List[BaseTool],
    registry: Optional[Dict[str, BaseTool]] = None,
    verbose: bool = False,
) -> List[BaseTool]:
    """
    Ensure connectivity by **additive expansion** -- keep every FAISS-selected
    tool and *top up* the selection with the node tools that complete each
    selected relation's endpoint coverage.

    Rationale
    ---------
    The previous behaviour was subtractive: a relation tool was DROPPED if
    its endpoint node labels did not overlap with the labels already covered
    by the selected *node* tools.  That penalty cascaded badly -- one weak
    FAISS hit on the node side caused otherwise-relevant relation tools to
    disappear from the NER agent, which then could not lookup the entities
    they were supposed to resolve.  Empirically this regressed PSJS on
    cypherbench_augmented (0.6397 -> 0.5721 with the agent enabled).

    The new behaviour is additive and never deletes anything:
      - Every tool the caller passed in is kept (FAISS already ranked them).
      - For each selected relation tool, we look up its endpoint node labels
        from the connectivity map.
      - For each endpoint label that is NOT already covered by a selected
        node tool, we scan the full registry for a matching node tool and
        append it to the result.

    Worst-case cost is bounded by the number of endpoint labels demanded by
    the selected relations (typically 1-4 extra tools), so the agent's
    context never explodes.

    Algorithm
    ---------
    1. Build a ``{rel_type: {labels}}`` connectivity map from the full
       registry (preferred source: ``schema_meta.json``; fallback: structural
       rel tool descriptions).
    2. ``covered``  = labels already supplied by selected NODE tools.
    3. ``demanded`` = labels referenced by selected RELATION tools' endpoints.
    4. ``missing``  = demanded - covered.
    5. For each label in ``missing`` (sorted for log stability), find the
       first registry node tool that covers it and append it (deduped by
       tool name).

    Parameters
    ----------
    selected_tools : Tools returned by :func:`select_tools_for_query`.
    registry       : Full tool registry.  When *None*, the module-level
                     singleton ``_registry`` is used.
    verbose        : Log which tools were appended and why.

    Returns
    -------
    List[BaseTool]
        Selected tools (original order) followed by the appended node tools
        (sorted by the missing label they cover, for determinism).

    Example
    -------
    Suppose the query is *"who played Neo in The Matrix"* and FAISS returns::

        [get_acted_in_roles, get_movie_title]

    ============== ====================================== ============
    Selected tool  Kind / endpoint labels                 Coverage role
    ============== ====================================== ============
    get_acted_in_roles  rel-property, endpoints {Person, Movie}    demands
    get_movie_title     node tool,    labels {Movie}               covers Movie
    ============== ====================================== ============

    ``demanded = {Person, Movie}``, ``covered = {Movie}`` →
    ``missing = {Person}`` → append ``get_person_name`` (first node tool in
    the registry whose labels include ``Person``).

    Result: ``[get_acted_in_roles, get_movie_title, get_person_name]``
    """
    if registry is None:
        registry = _get_registry()

    # Build {rel_type → {label, …}} from the full registry
    rel_conn = _build_rel_connectivity_map(registry)

    # ── Step 1: labels currently covered by selected NODE tools ───────────────
    covered: Set[str] = set()
    for tool_obj in selected_tools:
        if not _is_rel_tool(tool_obj):
            covered.update(_get_tool_node_labels(tool_obj, rel_conn))

    # ── Step 2: labels demanded by selected RELATION tools' endpoints ─────────
    demanded: Set[str] = set()
    for tool_obj in selected_tools:
        if _is_rel_tool(tool_obj):
            demanded.update(_get_tool_node_labels(tool_obj, rel_conn))

    missing: Set[str] = demanded - covered

    # ── Step 3: top-up node tools for each missing endpoint label ─────────────
    seen_names: Set[str] = {t.name for t in selected_tools}
    appended:   List[BaseTool] = []

    # sorted() makes the append order deterministic across runs / dict orderings
    for label in sorted(missing):
        for cand in registry.values():
            if cand.name in seen_names:
                continue
            if _is_rel_tool(cand):
                continue
            if label in _get_tool_node_labels(cand, rel_conn):
                appended.append(cand)
                seen_names.add(cand.name)
                break  # one node tool per missing label is enough

    result = list(selected_tools) + appended

    if verbose:
        if appended:
            logger.info(
                f"filter_tools_by_connectivity (additive): "
                f"covered={sorted(covered)}  demanded={sorted(demanded)}  "
                f"missing={sorted(missing)}  →  appended {len(appended)} "
                f"node tool(s): {[t.name for t in appended]}"
            )
        else:
            logger.info(
                f"filter_tools_by_connectivity (additive): "
                f"covered={sorted(covered)}  demanded={sorted(demanded)}  "
                f"missing=∅  →  no top-up needed (kept {len(selected_tools)})."
            )

    return result


def _render_tool_section(tools: List[BaseTool]) -> str:
    """Render the 'Available tools' block for exactly *tools*, grouped
    into node / relationship-property / structural sections — matching
    the format that gen_system_prompt.py produces for the static NER_SP."""
    node_lines:   List[str] = []
    rel_p_lines:  List[str] = []
    struct_lines: List[str] = []

    for t in tools:
        desc = (t.description or "").strip()
        line = f"  {t.name:<34}  {desc[:72]}"

        if "via (:" in desc:
            struct_lines.append(line)
            continue

        m = _RE_NODE_DESC.search(desc)
        if m and _RE_ALL_CAPS.match(m.group(1)):
            rel_p_lines.append(line)
        else:
            node_lines.append(line)

    parts: List[str] = []
    if node_lines:
        parts.append("  ── Node property tools ──\n" + "\n".join(node_lines))
    if rel_p_lines:
        parts.append("  ── Relationship property tools ──\n" + "\n".join(rel_p_lines))
    if struct_lines:
        parts.append("  ── Structural traversal tools ──\n" + "\n".join(struct_lines))

    return "\n\n".join(parts) if parts else "  (no tools selected)"


_TOOL_LIST_PLACEHOLDER = "{tool_list}"


def _build_dynamic_prompt(selected_tools: List[BaseTool]) -> str:
    """Return a copy of NER_SP whose ``{tool_list}`` placeholder has been
    replaced with a rendering of *selected_tools*.

    ``gen_system_prompt.py`` emits NER_SP with a ``{tool_list}`` token in
    the "Available tools" section instead of a baked-in tool list, because
    the actual tools available to the NER agent are decided at runtime
    (after FAISS selection + connectivity filtering).  This function does
    the runtime substitution.

    Fallbacks (in order):
      1. Substitute the ``{tool_list}`` placeholder if present.
      2. Otherwise, treat NER_SP as a legacy prompt with an inline tool
         list and replace the section between "Available tools" and
         "Extraction rules" via regex.  Warn so the maintainer knows the
         prompt is stale.
      3. As a last resort, return NER_SP unchanged with a warning.
    """
    tool_block = _render_tool_section(selected_tools)

    # Preferred path — placeholder substitution.
    if _TOOL_LIST_PLACEHOLDER in NER_SP:
        return NER_SP.replace(_TOOL_LIST_PLACEHOLDER, tool_block, 1)

    # Legacy path — older prompts that baked the tool list inline.
    new_prompt, n = re.subn(
        r"(Available tools\n[─\-]+\n).*?(\n\nExtraction rules)",
        lambda m: m.group(1) + tool_block + m.group(2),
        NER_SP,
        count=1,
        flags=re.DOTALL,
    )
    if n > 0:
        logger.warning(
            "_build_dynamic_prompt: NER_SP has no {tool_list} placeholder; "
            "falling back to legacy regex substitution. "
            "Re-run `python gen_system_prompt.py` to regenerate prompts.py."
        )
        return new_prompt

    logger.warning(
        "_build_dynamic_prompt: could not locate {tool_list} placeholder "
        "or 'Available tools' section in NER_SP — falling back to "
        "unmodified NER_SP."
    )
    return NER_SP


