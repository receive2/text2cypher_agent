def _parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description=(
            "Generate LangChain @tool functions from a Neo4j schema "
            "into two Python files."
        )
    )
    p.add_argument(
        "--node-output",
        default=str(GENERATED_NODE_TOOLS),
        metavar="PATH",
        help=f"Output path for node tools (default: {GENERATED_NODE_TOOLS})",
    )
    p.add_argument(
        "--rel-output",
        default=str(GENERATED_REL_TOOLS),
        metavar="PATH",
        help=f"Output path for relation tools (default: {GENERATED_REL_TOOLS})",
    )
    p.add_argument(
        "--database",
        default=os.getenv("NEO4J_DATABASE", "neo4j"),
        metavar="DB",
        help="Neo4j database name (default: $NEO4J_DATABASE or 'neo4j')",
    )
    p.add_argument(
        "--meta",
        default=str(SCHEMA_META),
        metavar="PATH",
        help=f"Path to schema_meta.json (default: {SCHEMA_META})",
    )
    return p.parse_args()


def main() -> None:
    global _schema_meta
    args = _parse_args()

    # Load schema_meta.json so _guess_id_property() can use id_property
    _schema_meta = _load_schema_meta(args.meta)
    if _schema_meta:
        labels = list(_schema_meta.get("nodes", {}).keys())
        print(f"Loaded schema_meta.json  (labels: {labels})", flush=True)
    else:
        print("No schema_meta.json found — using heuristic id_property guessing.", flush=True)

    print("Connecting to Neo4j …", flush=True)
    driver = _get_driver()

    try:
        db = args.database
        print(f"Introspecting schema  (database={db!r}) …", flush=True)

        node_pairs       = list_node_pairs(driver, db)
        rel_prop_pairs   = list_rel_property_pairs(driver, db)
        structural_rels  = list_structural_relations(driver, db)

    finally:
        driver.close()

    print(
        f"  {len(node_pairs):>3d}  node (label, property) pairs\n"
        f"  {len(rel_prop_pairs):>3d}  relationship property pairs\n"
        f"  {len(structural_rels):>3d}  unique relationship patterns",
        flush=True,
    )

    # Pass structural_rels into the node generator so name-class docstrings
    # get relational-hint clauses ("has cast member X", "directed by X", ...)
    # derived from the graph's actual rel patterns. This is what makes
    # Person.name discoverable when the question uses relational phrasings
    # — see _render_node_tool for the failure mode being patched.
    n_node = generate_node_tools_file(
        node_pairs, args.node_output,
        structural_relations=structural_rels,
    )
    print(f"\n✓  {n_node:>3d} node tools  →  {args.node_output}", flush=True)

    n_rel = generate_rel_tools_file(rel_prop_pairs, structural_rels, args.rel_output)
    print(f"✓  {n_rel:>3d} rel  tools  →  {args.rel_output}", flush=True)


if __name__ == "__main__":
    main()
