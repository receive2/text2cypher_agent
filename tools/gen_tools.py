def _parse_primary_label(node_type: str) -> str:
    """
    Extract the primary label from a nodeType string, stripping any
    backtick quoting that Neo4j may include.

    Examples::

        ':Movie'           → 'Movie'
        ':`Movie`'         → 'Movie'
        ':Person:Employee' → 'Person'   (first label)
        'Movie'            → 'Movie'    (bare label, no colon prefix)
    """
    if node_type.startswith(":"):
        parts = [p.strip().strip("`") for p in node_type.split(":") if p.strip()]
        return parts[0] if parts else node_type.strip("`")
    return node_type.strip("`")


def _camel_to_snake(name: str) -> str:
    """
    Convert CamelCase (or mixedCase) to snake_case.

    Examples::

        'JobPosting' → 'job_posting'
        'tagline'    → 'tagline'
        'firstName'  → 'first_name'
    """
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    return s.lower()


def _safe_ident(s: str) -> str:
    """
    Replace every non-alphanumeric character with ``_``, collapse runs,
    strip leading/trailing underscores, and lower-case.
    """
    s = re.sub(r"[^a-zA-Z0-9]", "_", s)
    s = re.sub(r"_+", "_", s)
    return s.strip("_").lower()


def _label_snake(label: str) -> str:
    """Convert a node label to a snake_case identifier fragment."""
    return _camel_to_snake(_safe_ident(label))


def _clean_rel_type(raw: str) -> str:
    """
    Strip Neo4j formatting artefacts from a relationship type string.

    Neo4j's ``db.schema.relTypeProperties()`` may return the type wrapped in
    backticks and prefixed with a colon, e.g. `` :`ACTED_IN` ``.
    This helper normalises all variants to the bare type name, e.g. ``ACTED_IN``.
    """
    s = raw.strip()           # remove surrounding whitespace
    s = s.strip("`")          # remove wrapping backticks
    s = s.lstrip(":")         # remove leading colon (`:ACTED_IN` → `ACTED_IN`)
    s = s.strip("`")          # remove any remaining inner backticks
    return s


def _rel_snake(rel_type: str) -> str:
    """
    Convert a relationship type (ALL_CAPS, possibly prefixed with ``:`` or
    wrapped in backticks) to a safe snake_case Python identifier fragment.

    Examples::

        'ACTED_IN'        → 'acted_in'
        ':ACTED_IN'       → 'acted_in'
        ':`ACTED_IN`'     → 'acted_in'
        'HAS_WORKED_FOR'  → 'has_worked_for'
    """
    return _safe_ident(_clean_rel_type(rel_type))


def _prop_snake(prop: str) -> str:
    """Convert a property name to snake_case."""
    return _camel_to_snake(prop)


def _unique_name(base: str, seen: Set[str]) -> str:
    """
    Return *base* if not already taken; otherwise append ``_2``, ``_3`` …
    Mutates *seen* by adding the returned name.
    """
    name = base
    counter = 2
    while name in seen:
        name = f"{base}_{counter}"
        counter += 1
    seen.add(name)
    return name


