def generate_node_tools_file(
    node_pairs: List[Tuple[str, str]],
    output_path: Union[str, Path],
    meta_path: Union[str, Path] = SCHEMA_META,
    structural_relations: Optional[List[Tuple[str, str, str]]] = None,
) -> int:
    """
    Write ``generated_node_tools.py``.

    When *meta_path* points to a valid ``schema_meta.json``, topics for each
    node property are read from it instead of inferred by heuristic.

    *structural_relations* (optional) carries the
    ``(rel_type, from_label, to_label)`` triples from
    :func:`list_structural_relations`. When supplied, name-class
    docstrings receive relational-hint clauses derived from these
    triples (e.g. Person.name picks up "has cast member X / directed by
    X / written by X"), which fixes the
    "tool buried below top-K when question is relational" failure mode
    observed on the partial-name probe. Caller is expected to pass it;
    defaulting to ``None`` keeps the legacy contract for any external
    importer of this function.

    Returns the number of @tool functions written.
    """
    global _schema_meta
    if not _schema_meta:
        _schema_meta = _load_schema_meta(meta_path)

    seen_names: Set[str] = set()
    blocks: List[str] = []

    for label, prop in node_pairs:
        base      = f"get_{_label_snake(label)}_{_prop_snake(prop)}"
        func_name = _unique_name(base, seen_names)
        blocks.append(_render_node_tool(
            func_name, label, prop,
            structural_relations=structural_relations,
        ))

    content = _NODE_HEADER + "\n\n".join(blocks) + "\n"
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as fh:
        fh.write(content)

    return len(blocks)


def generate_rel_tools_file(
    rel_prop_pairs: List[Tuple[str, str]],
    structural_relations: List[Tuple[str, str, str]],
    output_path: Union[str, Path],
    meta_path: Union[str, Path] = SCHEMA_META,
) -> int:
    """
    Write ``generated_rel_tools.py``.

    The file has two clearly separated sections:

    * **Part 1** – relationship property tools (``search_rel_tool``).
    * **Part 2** – structural traversal tools for property-less relationships
      (``search_tool`` on the end node).

    When *meta_path* points to a valid ``schema_meta.json``, the
    ``id_property`` for each label is read from it instead of guessed.

    Returns the total number of @tool functions written.
    """
    global _schema_meta
    if not _schema_meta:
        _schema_meta = _load_schema_meta(meta_path)
    seen_names: Set[str] = set()
    blocks: List[str]    = []

    # ── Part 1: relationship property tools ───────────────────────────────────
    if rel_prop_pairs:
        blocks.append(
            "# " + "─" * 72 + "\n"
            "# Part 1 — Relationship PROPERTY tools\n"
            "#          Search canonical values stored on relationship objects.\n"
            "# " + "─" * 72
        )
        for rel_type, prop in rel_prop_pairs:
            base      = f"get_{_rel_snake(rel_type)}_{_prop_snake(prop)}"
            func_name = _unique_name(base, seen_names)
            blocks.append(_render_rel_property_tool(func_name, rel_type, prop))

    # ── Part 2: structural (property-less) relationship tools ─────────────────
    # Exclude rel types that already have dedicated property tools above.
    rels_with_props: Set[str] = {rt for rt, _ in rel_prop_pairs}
    pure_structural = [
        (rt, fl, tl)
        for rt, fl, tl in structural_relations
        if rt not in rels_with_props
    ]

    if pure_structural:
        blocks.append(
            "\n\n# " + "─" * 72 + "\n"
            "# Part 2 — Structural TRAVERSAL tools\n"
            "#          No properties on the relationship itself; searches the\n"
            "#          end-node's primary identifying property instead.\n"
            "# " + "─" * 72
        )
        for rel_type, from_label, to_label in pure_structural:
            base      = f"get_{_rel_snake(rel_type)}_relation"
            func_name = _unique_name(base, seen_names)
            blocks.append(
                _render_structural_rel_tool(func_name, rel_type, from_label, to_label)
            )

    content = _REL_HEADER + "\n\n".join(blocks) + "\n"
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as fh:
        fh.write(content)

    # Count only @tool blocks (skip comment-only separator blocks)
    return sum(1 for b in blocks if b.startswith("@tool"))


