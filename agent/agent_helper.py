def _to_list(v: Any) -> List[Any]:
    """Normalize any scalar / list-ish value into a plain Python list."""
    if v is None:
        return []
    if isinstance(v, list):
        return v
    if isinstance(v, tuple) or isinstance(v, set):
        return list(v)
    return [v]


def _flatten_and_dedupe(v: Any) -> List[Any]:
    """
    Flatten ONE level of nested lists and drop ``None`` / duplicates while
    preserving first-seen order.  Tolerates legacy ``[[v1], [v2]]`` outputs
    produced by older NER prompts.
    """
    out:  List[Any] = []
    seen: set      = set()
    for item in _to_list(v):
        inner = item if isinstance(item, (list, tuple)) else [item]
        for x in inner:
            if x is None:
                continue
            try:
                key = json.dumps(x, ensure_ascii=False, sort_keys=True)
            except TypeError:
                key = repr(x)
            if key in seen:
                continue
            seen.add(key)
            out.append(x)
    return out


def _collapse_singletons(d: Dict[str, Any]) -> Dict[str, Any]:
    """``{"k": [v]}`` → ``{"k": v}``; multi-value lists are preserved; empty
    lists drop the key entirely."""
    out: Dict[str, Any] = {}
    for k, v in d.items():
        flat = _flatten_and_dedupe(v) if isinstance(v, (list, tuple)) else _flatten_and_dedupe([v])
        if not flat:
            continue
        out[k] = flat[0] if len(flat) == 1 else flat
    return out


def extract_content(input_string: str) -> str:
    """
    Parse the agent's final message into a canonical JSON string of the form::

        {"Label.property": <scalar>}              # single value
        {"Label.property": [v1, v2, ...]}         # multiple values

    Guarantees:
      - Returns a valid JSON string (use ``json.loads`` to get a dict back).
      - Single-value entries surface as bare scalars (no ``[...]`` wrapper).
      - Multi-value entries keep their JSON array form.
      - Legacy nested ``[[v1], [v2]]`` outputs are flattened automatically.
      - Returns ``"{}"`` on any failure so downstream code never crashes.
    """
    if not input_string:
        return "{}"

    text = input_string.strip()

    # Strip optional markdown code fences (```json ... ``` or ```python ... ```)
    m = re.search(r"```(?:python|json)?\s*(.*?)\s*```", text, re.DOTALL)
    if m:
        text = m.group(1).strip()

    # Try JSON first, then Python literal (to tolerate single quotes, etc.)
    parsed: Optional[Dict[str, Any]] = None
    for loader in (json.loads, ast.literal_eval):
        try:
            obj = loader(text)
            if isinstance(obj, dict):
                parsed = obj
                break
        except Exception:
            continue

    if parsed is None:
        return "{}"

    normalized = _collapse_singletons(parsed)
    return json.dumps(normalized, ensure_ascii=False)


def get_ner(
    prompt: str,
    verbose: bool = False,
    llm_obj: Optional[BaseChatModel] = None,
) -> str:
    """
    Run the NER agent on `prompt` and return a canonical JSON string.

    Pass ``llm_obj`` to swap in a non-default chat model (e.g. Claude Opus
    via ``build_llm(provider='anthropic')``) without touching the module-level
    default.
    """
    inputs = {"messages": [("user", f"{prompt}")]}
    agent_graph = create_agent(llm_obj=llm_obj)

    message = None
    for msgs in agent_graph.stream(inputs, stream_mode="values"):
        tools_messages = [m for m in msgs["messages"] if isinstance(m, ToolMessage)]
        message = msgs["messages"][-1]

        if verbose:
            if isinstance(message, tuple):
                logger.info(message)
            else:
                message.pretty_print()

            if tools_messages:
                for tool_msg in tools_messages:
                    logger.info(tool_msg.content)

    if message is None:
        return "{}"

    return extract_content(message.content)


def get_ner_dict(
    prompt: str,
    verbose: bool = False,
    llm_obj: Optional[BaseChatModel] = None,
) -> Dict[str, Any]:
    """Convenience wrapper: return the entity dict as a real Python dict.

    Values follow the scalar-or-list convention: a bare scalar for a single
    match, a list for multiple matches.  ``{}`` on parse failure.
    """
    raw = get_ner(prompt, verbose=verbose, llm_obj=llm_obj)
    try:
        obj = json.loads(raw)
        return obj if isinstance(obj, dict) else {}
    except Exception:
        return {}


