# ─────────────────────────────────────────────────────────────────────────────
# Provider-agnostic LLM factory
# ─────────────────────────────────────────────────────────────────────────────
# ``build_llm`` returns any LangChain ``BaseChatModel`` (ChatOpenAI,
# AzureChatOpenAI, ChatAnthropic, …).  All downstream call sites
# (``create_react_agent``, ``GraphCypherQAChain.from_llm``) accept any
# ``BaseChatModel``, so swapping providers does not require changes elsewhere.
#
# Provider selection priority (when ``provider`` is left as ``"auto"``):
#   1. ``LLM_PROVIDER`` env var, if set  ("openai" | "azure" | "anthropic")
#   2. Azure OpenAI    — when AZURE_OPENAI_{ENDPOINT,API_KEY,DEPLOYMENT} are set
#   3. Anthropic       — when ANTHROPIC_API_KEY is set and OPENAI_API_KEY is not
#   4. Public OpenAI   — fallback
#
# Examples:
#   llm_gpt    = build_llm(provider="openai",        model="gpt-4.1")
#   llm_opus   = build_llm(provider="anthropic",     model="claude-opus-4-20250514")
#   llm_azure  = build_llm(provider="azure")          # uses AZURE_OPENAI_DEPLOYMENT
#   llm_llama  = build_llm(provider="hf_compatible", model="llama-8b-hf")
#                # ↑ ``model`` is a key into config.MODEL_REGISTRY
#
# About the ``hf_compatible`` provider
# ────────────────────────────────────
# All targets (HF serverless router, HF Inference Endpoints with TGI, Groq,
# Together, Fireworks, …) expose an OpenAI-compatible
# ``/v1/chat/completions`` endpoint, so a single OpenAI SDK client works for
# every one of them — only ``base_url``, ``api_key``, and ``model`` change.
# ``ChatOpenAI`` from ``langchain-openai`` IS that openai-SDK-backed client
# wrapped as a ``BaseChatModel``; pointing it at any ``base_url`` turns it
# into an OpenAI-compatible client for that endpoint.  This lets us reuse the
# rest of the LangChain pipeline (``create_react_agent``,
# ``GraphCypherQAChain``) without any extra glue code.
# ─────────────────────────────────────────────────────────────────────────────

# Default Anthropic model — overridable via the ANTHROPIC_MODEL env var.
DEFAULT_ANTHROPIC_MODEL = "claude-opus-4-20250514"


def _build_http_client() -> httpx.Client:
    """Construct a shared httpx client honoring TRUST_ENV / proxy settings."""
    trust_env = os.getenv("TRUST_ENV", "1") != "0"
    return httpx.Client(
        timeout=httpx.Timeout(60.0, connect=10.0),
        trust_env=trust_env,
    )


def _resolve_provider(provider: str) -> str:
    """Resolve the ``"auto"`` sentinel into a concrete provider string."""
    if provider and provider != "auto":
        return provider.lower()

    env_provider = os.getenv("LLM_PROVIDER", "").strip().lower()
    if env_provider in {"openai", "azure", "anthropic", "hf_compatible"}:
        return env_provider

    if (
        os.getenv("AZURE_OPENAI_ENDPOINT")
        and os.getenv("AZURE_OPENAI_API_KEY")
        and os.getenv("AZURE_OPENAI_DEPLOYMENT")
    ):
        return "azure"

    if os.getenv("ANTHROPIC_API_KEY") and not os.getenv("OPENAI_API_KEY"):
        return "anthropic"

    return "openai"


def _build_openai_llm(
    model: Optional[str],
    temperature: float,
    http_client: httpx.Client,
    **extra: Any,
) -> ChatOpenAI:
    return _cache_mixin(ChatOpenAI, anthropic=False)(
        model=model or os.getenv("OPENAI_MODEL", "gpt-4.1"),
        api_key=os.getenv("OPENAI_API_KEY"),
        temperature=temperature,
        timeout=60,
        max_retries=2,
        base_url=os.getenv("OPENAI_BASE_URL") or None,
        http_client=http_client,
        **extra,
    )


def _build_azure_llm(
    model: Optional[str],
    temperature: float,
    http_client: httpx.Client,
    **extra: Any,
) -> BaseChatModel:
    azure_endpoint = os.environ["AZURE_OPENAI_ENDPOINT"]
    azure_key = os.environ["AZURE_OPENAI_API_KEY"]
    azure_deployment = model or os.environ["AZURE_OPENAI_DEPLOYMENT"]

    base_url = azure_endpoint.rstrip("/") + "/openai/v1/"
    try:
        return _cache_mixin(ChatOpenAI, anthropic=False)(
            model=azure_deployment,
            api_key=azure_key,
            base_url=base_url,
            temperature=temperature,
            timeout=60,
            max_retries=2,
            http_client=http_client,
            **extra,
        )
    except Exception:
        return _cache_mixin(AzureChatOpenAI, anthropic=False)(
            azure_deployment=azure_deployment,
            api_version=os.getenv("AZURE_OPENAI_API_VERSION", "2024-05-01-preview"),
            api_key=azure_key,
            azure_endpoint=azure_endpoint,
            temperature=temperature,
            timeout=60,
            max_retries=2,
            http_client=http_client,
            **extra,
        )


# ── Prompt-cache plumbing ────────────────────────────────────────────────────
# Prompts carry a CACHE_BREAK marker at the static/variable boundary (see
# agent/prompt_cache.py). These thin subclasses resolve it at the last possible
# moment — inside the chat model — so every call site and every LangChain chain
# is covered without any of them knowing about caching. `_generate` is the one
# funnel all sync paths go through; `_agenerate` mirrors it for async.
@lru_cache(maxsize=None)
def _cache_mixin(base, anthropic: bool):
    class _PromptCached(base):                      # type: ignore[misc,valid-type]
        """`base` plus CACHE_BREAK resolution. The model sees identical text."""

        def _generate(self, messages, stop=None, run_manager=None, **kwargs):
            messages = prompt_cache.prepare_messages(messages, anthropic)
            return super()._generate(messages, stop=stop, run_manager=run_manager, **kwargs)

        async def _agenerate(self, messages, stop=None, run_manager=None, **kwargs):
            messages = prompt_cache.prepare_messages(messages, anthropic)
            return await super()._agenerate(messages, stop=stop, run_manager=run_manager, **kwargs)

    _PromptCached.__name__ = f"PromptCached{base.__name__}"
    return _PromptCached


def _build_anthropic_llm(
    model: Optional[str],
    temperature: float,
    **extra: Any,
) -> BaseChatModel:
    if ChatAnthropic is None:
        raise ImportError(
            "langchain-anthropic is not installed.  Run "
            "`pip install langchain-anthropic` to enable provider='anthropic'."
        )
    api_key = os.getenv("ANTHROPIC_API_KEY")
    if not api_key:
        raise RuntimeError(
            "ANTHROPIC_API_KEY is not set in the environment.  Add it to your "
            ".env file before requesting provider='anthropic'."
        )

    # Anthropic caching is opt-in: the static prefix must arrive as its own
    # cache_control block, which this subclass does from the CACHE_BREAK marker.
    _Cls = _cache_mixin(ChatAnthropic, anthropic=True)
    return _Cls(
        model=model or os.getenv("ANTHROPIC_MODEL", DEFAULT_ANTHROPIC_MODEL),
        api_key=api_key,
        temperature=temperature,
        timeout=60,
        max_retries=2,
        **extra,
    )


def _build_hf_compatible_llm(
    model: Optional[str],
    temperature: float,
    http_client: httpx.Client,
    **extra: Any,
) -> BaseChatModel:
    """
    Build a chat client for any OpenAI-compatible HTTP endpoint declared in
    ``config.MODEL_REGISTRY`` — HF serverless router, HF Inference Endpoints
    (TGI), Groq, Together, Fireworks, etc.

    The ``model`` argument is a *registry key* (e.g. ``"llama-8b-hf"`` or
    ``"my-svl-cypher-lora-v1"``) — NOT a raw model id.  We look the key up in
    MODEL_REGISTRY to get the actual ``base_url`` / ``api_key_env`` / ``model``
    triple, then instantiate ``ChatOpenAI`` (LangChain's wrapper around the
    openai SDK) pointed at that endpoint.

    Why ``ChatOpenAI`` and not the bare ``openai.OpenAI`` client?
    ``ChatOpenAI`` *is* the openai-SDK-backed chat client, just dressed as a
    LangChain ``BaseChatModel`` so the rest of the pipeline
    (``create_react_agent``, ``GraphCypherQAChain.from_llm``) keeps working
    unchanged.  Setting ``base_url`` makes it talk to any OpenAI-compatible
    server, exactly like the snippet from the HF docs:

        from openai import OpenAI
        client = OpenAI(base_url="https://router.huggingface.co/v1",
                        api_key="hf_xxx")

    Notes on the ``model`` field that gets sent in the request body:
      * HF Inference Endpoints (TGI):  the URL itself pins the model, so the
        registry's ``model`` is just ``"tgi"`` — TGI ignores the field but
        the OpenAI request schema requires it.
      * HF serverless router: ``model`` MUST be the full Hub repo id, e.g.
        ``meta-llama/Llama-3.1-8B-Instruct`` (the router uses it for routing).
      * Other providers (Groq, Together, …): use whatever id the provider
        documents.
    """
    if not model:
        raise ValueError(
            "provider='hf_compatible' requires a model key (a key into "
            "config.MODEL_REGISTRY), e.g. model='llama-8b-hf'."
        )

    entry = MODEL_REGISTRY.get(model)
    if entry is None:
        available = ", ".join(sorted(MODEL_REGISTRY.keys())) or "<empty>"
        raise KeyError(
            f"Model key {model!r} not found in MODEL_REGISTRY.  "
            f"Available keys: {available}.  Add a new entry in config.py "
            "to register a new endpoint."
        )

    base_url    = entry["base_url"]
    api_key_env = entry["api_key_env"]
    model_id    = entry["model"]   # value sent in the request body's ``model``

    api_key = os.getenv(api_key_env)
    if not api_key:
        raise RuntimeError(
            f"Environment variable {api_key_env!r} is not set.  "
            f"Add it to your .env file before requesting model={model!r}."
        )

    # ChatOpenAI uses the openai SDK under the hood; pointing it at any
    # OpenAI-compatible base_url turns it into a client for that server.
    return _cache_mixin(ChatOpenAI, anthropic=False)(
        model=model_id,
        api_key=api_key,
        base_url=base_url,
        temperature=temperature,
        timeout=60,
        max_retries=2,
        http_client=http_client,
        **extra,           # forwards max_tokens, top_p, model_kwargs, etc.
    )


def build_llm(
    provider: str = "auto",
    model: Optional[str] = None,
    temperature: float = 0,
    **extra: Any,
) -> BaseChatModel:
    """
    Build a LangChain chat model for the requested provider.

    Parameters
    ----------
    provider : {"auto", "openai", "azure", "anthropic", "hf_compatible"}
        Which provider to instantiate.  ``"auto"`` (default) picks one based
        on env vars — see the priority list at the top of this section.
        ``"hf_compatible"`` routes through ``config.MODEL_REGISTRY`` and
        works with any OpenAI-compatible server (HF router, HF Inference
        Endpoints/TGI, Groq, Together, Fireworks, …).
    model : Optional[str]
        Model name / deployment override.  When ``None``, falls back to the
        provider-specific env var (``OPENAI_MODEL``, ``AZURE_OPENAI_DEPLOYMENT``,
        ``ANTHROPIC_MODEL``) or a sensible default.  When ``provider`` is
        ``"hf_compatible"``, this is interpreted as a key into MODEL_REGISTRY.
    temperature : float
        Sampling temperature (default 0 for deterministic NER / Cypher).
    **extra :
        Forwarded verbatim to the underlying chat-model constructor
        (e.g. ``max_tokens``, ``top_p``, ``model_kwargs``).

    Returns
    -------
    BaseChatModel
        Any concrete LangChain chat model — caller code should treat it as
        opaque and only rely on the ``BaseChatModel`` interface.
    """
    resolved = _resolve_provider(provider)
    http_client = _build_http_client()

    if resolved == "openai":
        return _build_openai_llm(model, temperature, http_client, **extra)
    if resolved == "azure":
        return _build_azure_llm(model, temperature, http_client, **extra)
    if resolved == "anthropic":
        return _build_anthropic_llm(model, temperature, **extra)
    if resolved == "hf_compatible":
        return _build_hf_compatible_llm(model, temperature, http_client, **extra)

    raise ValueError(
        f"Unknown LLM provider {provider!r}.  "
        "Expected one of: 'auto', 'openai', 'azure', 'anthropic', 'hf_compatible'."
    )


def build_llm_from_config(cfg: Dict[str, Any]) -> BaseChatModel:
    """
    Build an LLM from a config dict (e.g. ``NER_LLM_CONFIG`` from ``config.py``).

    The dict is shallow-copied and forwarded to :func:`build_llm` as keyword
    arguments — ``provider`` and ``model`` are recognised explicitly; any
    additional keys (e.g. ``temperature``, ``max_tokens``) flow through to the
    underlying chat-model constructor.

    Returns the same instance on repeated calls with the same config object,
    so each stage's singleton stays singular.
    """
    cfg = dict(cfg)  # don't mutate the caller's dict
    provider    = cfg.pop("provider", "auto")
    model       = cfg.pop("model", None)
    temperature = cfg.pop("temperature", 0)
    return build_llm(
        provider=provider,
        model=model,
        temperature=temperature,
        **cfg,
    )


