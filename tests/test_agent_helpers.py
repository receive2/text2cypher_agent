@unittest.skipIf(_NER_MODULE is None, f"ner_agent_auto unavailable: {_NER_IMPORT_ERROR!r}")
class TestAdaptiveTopK(unittest.TestCase):
    """_adaptive_top_k sizes top_k by query complexity."""

    def setUp(self):
        self.f = _NER_MODULE._adaptive_top_k

    def test_floor_for_empty_query(self):
        # Empty query — return base unchanged.
        self.assertEqual(self.f("", base_top_k=10), 10)

    def test_simple_question_small_k(self):
        # Single entity, single relation → small k.
        k = self.f("Who directed Inception?", base_top_k=10)
        self.assertGreaterEqual(k, 3)
        self.assertLessEqual(k, 8)

    def test_compound_question_higher_k(self):
        simple = self.f("Who directed Inception?", base_top_k=10)
        compound = self.f(
            "How many movies have either won the Amanda Award for "
            "Best Foreign Feature Film or feature Elijah Wood in their cast?",
            base_top_k=10,
        )
        # Compound should not be smaller than simple.
        self.assertGreaterEqual(compound, simple)

    def test_clamped_to_max(self):
        # Adversarial: many entities + many relations should still clamp at 8.
        massive = (
            "From 1999 to 2010, who directed 'Inception' and 'The Matrix' "
            "and produced 'Memento' and acted in 'Tenet' and 'Interstellar'?"
        )
        k = self.f(massive, base_top_k=10)
        self.assertLessEqual(k, 8)

    def test_respects_small_base_top_k(self):
        # Caller asks for tiny budget; adaptive must not blow it up beyond 2x.
        k = self.f(
            "How many movies have either won the Amanda Award or feature "
            "Elijah Wood?",
            base_top_k=2,
        )
        self.assertLessEqual(k, 4)


