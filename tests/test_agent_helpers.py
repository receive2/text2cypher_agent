class TestDropEmbeddingToolNames(unittest.TestCase):
    """_drop_embedding_tool_names L1/L2/L3 filtering."""

    def _make_tool(self, name: str, description: str = ""):
        """Build a minimal tool-like object that satisfies attribute access."""
        class FakeTool:
            def __init__(self, n, d):
                self.name = n
                self.description = d
        return FakeTool(name, description)

    def setUp(self):
        self.f = _NER_MODULE._drop_embedding_tool_names

    def test_L1_drops_name_suffix_embedding(self):
        reg = {
            "get_movie_title": self._make_tool(
                "get_movie_title",
                "Look up canonical Movie.title values.",
            ),
            "get_movie_title_embedding": self._make_tool(
                "get_movie_title_embedding",
                "Look up canonical Movie.title_embedding values.",
            ),
        }
        out = self.f(reg)
        self.assertIn("get_movie_title", out)
        self.assertNotIn("get_movie_title_embedding", out)

    def test_L1_drops_name_suffix_vector(self):
        reg = {
            "get_person_name_vector": self._make_tool(
                "get_person_name_vector",
                "Look up canonical Person.name_vector values.",
            ),
        }
        self.assertEqual(self.f(reg), {})

    def test_L2_drops_when_description_mentions_embedding(self):
        # The L1 name check misses 'unrelated_name', but the description
        # contains 'embedding' so L2 catches it.
        reg = {
            "unrelated_name": self._make_tool(
                "unrelated_name",
                "Look up canonical Movie.foo embedding values.",
            ),
        }
        self.assertEqual(self.f(reg), {})

    def test_clean_tool_survives(self):
        reg = {
            "get_movie_title": self._make_tool(
                "get_movie_title",
                "Look up canonical Movie.title values.",
            ),
        }
        out = self.f(reg)
        self.assertIn("get_movie_title", out)


@unittest.skipIf(_NER_MODULE is None, f"ner_agent_auto unavailable: {_NER_IMPORT_ERROR!r}")
class TestFailureTrackingWrapper(unittest.TestCase):
    """_wrap_tools_with_failure_tracking short-circuits after N empty results."""

    def _make_returning_tool(self, *return_values):
        """Build a stub tool whose .invoke() returns return_values[i] in order."""
        from langchain_core.tools import StructuredTool

        calls = {"i": 0, "log": []}

        def _func(user_query: str):
            i = calls["i"]
            calls["i"] += 1
            calls["log"].append(user_query)
            return return_values[i] if i < len(return_values) else []

        tool = StructuredTool.from_function(
            func=_func,
            name="get_test_tool",
            description="Test tool",
        )
        return tool, calls

    def test_short_circuits_after_two_empty_results(self):
        tool, calls = self._make_returning_tool([], [], ["should_not_be_called"])
        wrapped = _NER_MODULE._wrap_tools_with_failure_tracking([tool])
        w = wrapped[0]

        # 1st call — empty, counter=1, real tool called.
        r1 = w.invoke({"user_query": "q1"})
        self.assertEqual(r1, [])
        # 2nd call — empty, counter=2, real tool called.
        r2 = w.invoke({"user_query": "q2"})
        self.assertEqual(r2, [])
        # 3rd call — short-circuited, real tool MUST NOT be invoked.
        r3 = w.invoke({"user_query": "q3"})
        self.assertEqual(len(r3), 1)
        self.assertIn("no_more_attempts", r3[0])
        self.assertEqual(calls["i"], 2)  # real tool was called exactly twice

    def test_resets_counter_on_non_empty_result(self):
        tool, calls = self._make_returning_tool([], ["hit"], [])
        wrapped = _NER_MODULE._wrap_tools_with_failure_tracking([tool])
        w = wrapped[0]

        self.assertEqual(w.invoke({"user_query": "q1"}), [])      # streak=1
        self.assertEqual(w.invoke({"user_query": "q2"}), ["hit"])  # streak=0
        self.assertEqual(w.invoke({"user_query": "q3"}), [])      # streak=1
        # Real tool was called 3× (streak never reached 2 consecutively).
        self.assertEqual(calls["i"], 3)

    def test_treats_whitespace_only_strings_as_empty(self):
        tool, calls = self._make_returning_tool(["   "], [""], ["nope"])
        wrapped = _NER_MODULE._wrap_tools_with_failure_tracking([tool])
        w = wrapped[0]

        w.invoke({"user_query": "q1"})
        w.invoke({"user_query": "q2"})
        r3 = w.invoke({"user_query": "q3"})
        self.assertIn("no_more_attempts", r3[0])
        self.assertEqual(calls["i"], 2)

    def test_counters_isolated_per_wrap_call(self):
        # Two separate wrap calls produce wrappers with independent counters.
        tool, calls = self._make_returning_tool([], [], [], [])
        w1 = _NER_MODULE._wrap_tools_with_failure_tracking([tool])[0]
        w1.invoke({"user_query": "q1"})
        w1.invoke({"user_query": "q2"})
        # New wrap → fresh counter; first call is NOT short-circuited.
        w2 = _NER_MODULE._wrap_tools_with_failure_tracking([tool])[0]
        r = w2.invoke({"user_query": "q3"})
        self.assertEqual(r, [])  # real tool called, not short-circuit


