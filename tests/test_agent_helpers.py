class TestTokenFuzziness(unittest.TestCase):
    """_token_fuzziness picks 0/1/2 by token length."""

    def setUp(self):
        from neo4j_lib.neo4j_search import _token_fuzziness
        self.f = _token_fuzziness

    def test_short_token_zero(self):
        # < 5 chars → 0  (avoid the "Tom" → millions-of-matches blowup)
        self.assertEqual(self.f("Tom"), 0)
        self.assertEqual(self.f("NBA"), 0)
        self.assertEqual(self.f("a"), 0)
        self.assertEqual(self.f("Joe"), 0)

    def test_medium_token_one(self):
        # 5..10 chars → 1
        self.assertEqual(self.f("Hanks"), 1)
        self.assertEqual(self.f("Matrix"), 1)
        self.assertEqual(self.f("Inception"), 1)  # 9
        self.assertEqual(self.f("Documenta"), 1)  # 9

    def test_long_token_two(self):
        # > 10 chars → 2
        self.assertEqual(self.f("Revolutions"), 2)  # 11
        self.assertEqual(self.f("Documentary"), 2)  # 11
        self.assertEqual(self.f("Grindelwald"), 2)  # 11


class TestLuceneQueryAutoMode(unittest.TestCase):
    """_lucene_query_from_phrase fuzziness=None engages AUTO."""

    def setUp(self):
        from neo4j_lib.neo4j_search import _lucene_query_from_phrase
        self.f = _lucene_query_from_phrase

    def test_auto_short_token_no_suffix(self):
        # "Tom" → 0 → no suffix
        self.assertEqual(self.f("Tom", fuzziness=None), "Tom")

    def test_auto_medium_token_suffix_one(self):
        self.assertEqual(self.f("Hanks", fuzziness=None), "Hanks~1")

    def test_auto_long_token_suffix_two(self):
        self.assertEqual(self.f("Revolutions", fuzziness=None), "Revolutions~2")

    def test_auto_mixed_phrase(self):
        # "Tom Hanks Revolutions" → no~ , ~1, ~2
        self.assertEqual(
            self.f("Tom Hanks Revolutions", fuzziness=None),
            "Tom Hanks~1 Revolutions~2",
        )

    def test_explicit_fuzziness_one_preserved(self):
        # Legacy callers passing fuzziness=1 keep the historical behaviour.
        self.assertEqual(self.f("Tom", fuzziness=1), "Tom~1")
        self.assertEqual(self.f("Revolutions", fuzziness=1), "Revolutions~1")

    def test_explicit_fuzziness_zero_disables(self):
        self.assertEqual(self.f("Matrix", fuzziness=0), "Matrix")

    def test_lucene_specials_escaped(self):
        # Reserved chars in tokens must be escaped under all modes.
        out = self.f("foo:bar", fuzziness=None)
        # split on \w → ['foo', 'bar'] (colon is the boundary), each ~0
        self.assertEqual(out, "foo bar")


