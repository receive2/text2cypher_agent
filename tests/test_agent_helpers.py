# Progress heartbeat (eval/metrics_CypherBench.py)
# ──────────────────────────────────────────────────────────────────────────────
#
# The heartbeat is purely a side-effecting print helper, so we capture stdout
# and assert on the shape of the lines.  Goal: protect the contract that a
# stalled eval still leaves a "starting record N" line in the log.

class TestHeartbeatFormatter(unittest.TestCase):
    """Smoke-test the eval-loop heartbeat lines and ETA arithmetic."""

    @classmethod
    def setUpClass(cls):
        # The eval/metrics_CypherBench import chain pulls in agent_helper and
        # ner_agent_auto, which are already stubbed at module load above.  We
        # also need to stub neo4j_lib.safe_query since CypherBench imports it.
        if "neo4j_lib.safe_query" not in sys.modules:
            sq = types.ModuleType("neo4j_lib.safe_query")
            def _scr(*a, **k):
                return []
            class _TTOE(Exception):
                pass
            sq.safe_cypher_run = _scr
            sq.TransactionTimedOutError = _TTOE
            sys.modules["neo4j_lib.safe_query"] = sq
        from eval import metrics_CypherBench  # noqa: WPS433
        cls.mod = metrics_CypherBench

    def _capture(self, fn, *a, **k):
        import io
        import contextlib
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            fn(*a, **k)
        return buf.getvalue()

    def test_fmt_hms_seconds_only(self):
        self.assertEqual(self.mod._fmt_hms(0), "0s")
        self.assertEqual(self.mod._fmt_hms(45), "45s")

    def test_fmt_hms_minutes(self):
        self.assertEqual(self.mod._fmt_hms(125), "2m05s")

    def test_fmt_hms_hours(self):
        self.assertEqual(self.mod._fmt_hms(7325), "2h02m05s")

    def test_fmt_hms_handles_negative_and_none(self):
        self.assertEqual(self.mod._fmt_hms(-1), "--")
        self.assertEqual(self.mod._fmt_hms(None), "--")

    def test_start_line_includes_question(self):
        import time as _t
        out = self._capture(
            self.mod._heartbeat,
            1, 10, _t.time(),
            kind="start",
            qid="q1",
            question="who directed The Matrix?",
            every=1,
        )
        self.assertIn("▶ start", out)
        self.assertIn("qid=q1", out)
        self.assertIn("The Matrix", out)
        # boundary record always prints regardless of sampling
        self.assertIn("[   1/10]", out)

    def test_done_line_includes_running_ea_and_eta(self):
        import time as _t
        records = [{"ea": True}, {"ea": False}, {"ea": True}]
        out = self._capture(
            self.mod._heartbeat,
            3, 10, _t.time() - 30,
            kind="done",
            qid="q3",
            ea=True, em=False, psjs=0.9,
            elapsed=4.2,
            records_so_far=records,
            every=1,
        )
        self.assertIn("✔ done", out)
        self.assertIn("runEA=0.667", out)  # 2/3 EA hits
        self.assertIn("ETA=", out)
        self.assertIn("t=4.2s", out)

    def test_sampling_skips_middle_records(self):
        """When ``every=10`` and we're not at a boundary or error, the line
        should be suppressed.  Boundary (i==total) MUST still print so the
        operator sees the end of the run."""
        import time as _t
        out_mid = self._capture(
            self.mod._heartbeat,
            5, 100, _t.time(),
            kind="done", qid="q5", ea=True, em=True, psjs=1.0,
            elapsed=1.0, records_so_far=[{"ea": True}],
            every=10,
        )
        self.assertEqual(out_mid, "")  # suppressed

        out_end = self._capture(
            self.mod._heartbeat,
            100, 100, _t.time(),
            kind="done", qid="q100", ea=True, em=True, psjs=1.0,
            elapsed=1.0, records_so_far=[{"ea": True}],
            every=10,
        )
        self.assertIn("✔ done", out_end)  # boundary always prints

    def test_error_always_prints_even_when_sampled(self):
        """An error line MUST never be silently dropped by sampling."""
        import time as _t
        out_err = self._capture(
            self.mod._heartbeat,
            7, 100, _t.time(),
            kind="done", qid="q7", ea=False, em=False, psjs=0.0,
            err="timeout: 60s",
            elapsed=60.0, records_so_far=[{"ea": False}],
            every=10,
        )
        self.assertIn("err=timeout", out_err)


