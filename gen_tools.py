#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_tools.py
============
Introspects a live Neo4j database and emits two ready-to-import Python source
files containing LangChain ``@tool``-decorated functions:

  generated_node_tools.py
      One tool per (node label × property) pair.
      Each tool extracts a keyword from the user query with ``get_entity()``,
      then calls ``search_tool()`` to return canonical property values.

  generated_rel_tools.py
      • Part 1 – relationships WITH properties:
        One tool per (relationship type × property) pair.
        Calls ``search_rel_tool()`` (defined in neo4j_search.py).
      • Part 2 – structural (property-less) relationships:
        One tool per unique (rel_type, from_label, to_label) pattern.
        Calls ``search_tool()`` on the end-node's primary identifying property.

Usage
-----
  python gen_tools.py
  python gen_tools.py --node-output node_tools.py --rel-output rel_tools.py
  python gen_tools.py --database movies

Environment variables  (loaded from .env)
-----------------------------------------
  NEO4J_URI        bolt / neo4j+s URI
  NEO4J_USERNAME
  NEO4J_PASSWORD
  NEO4J_DATABASE   default: movies
"""

